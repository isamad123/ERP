using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using Erp.CodeGen.Design;

namespace Erp.CodeGen.Emit;

public sealed record ExpectedColumn(string Name, string Kind, string Type, bool NotNull, bool HasDefault, bool Generated, bool Sensitive, IReadOnlyList<string> EnumValues);

public sealed record ExpectedForeignKey(string Name, IReadOnlyList<string> Columns, string Target, IReadOnlyList<string> TargetColumns);

public sealed record ExpectedTable(
    string Database,
    string Schema,
    string Name,
    string Module,
    IReadOnlyList<string> Traits,
    IReadOnlyList<string> Requirements,
    string? PartitionColumn,
    IReadOnlyList<string> PrimaryKey,
    IReadOnlyList<ExpectedColumn> Columns,
    IReadOnlyList<string> Uniques,
    IReadOnlyList<string> Checks,
    IReadOnlyList<string> Exclusions,
    IReadOnlyList<ExpectedForeignKey> ForeignKeys,
    IReadOnlyList<string> Indexes,
    IReadOnlyList<string> Triggers,
    IReadOnlyList<string> AppendOnlyUpdatable,
    bool HasApi)
{
    public string FullName => Schema + "." + Name;
}

public sealed record ExpectedStub(string Schema, string Function, string Table, string Owner, string Rule);

public sealed record ExpectedCatalog(string Generated, string Release, IReadOnlyList<ExpectedTable> Tables, IReadOnlyList<ExpectedStub> Stubs)
{
    public static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
        DefaultIgnoreCondition = JsonIgnoreCondition.Never,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    public static ExpectedCatalog Load(string path) =>
        JsonSerializer.Deserialize<ExpectedCatalog>(File.ReadAllText(path), JsonOptions) ?? throw new InvalidDataException(path);
}

/// <summary>
/// The data design as the database must hold it, written for the tests: one entry per table with the columns, keys,
/// constraints, indexes and triggers the migrations must create (slice S1.02 item 6), and the placeholder register.
/// </summary>
public static class CatalogEmitter
{
    public const string CatalogPath = "tests/Erp.IntegrationTests/Generated/expected-catalog.json";
    public const string RegisterPath = "docs/registers/todo-stubs.md";

    public static void Emit(DesignModel model, OutputSet output)
    {
        var tables = model.Tables.Select(t => new ExpectedTable(
            t.Database == DatabaseKind.Tenant ? "tenant" : "control_plane",
            t.Schema,
            t.Name,
            t.Module,
            t.Traits,
            t.Requirements,
            t.Partition?.Column,
            t.PrimaryKey,
            t.Columns.Select(c => new ExpectedColumn(c.Name, c.Kind.ToString(), FormatType(c), c.Required, c.Default is not null, c.IsGenerated, c.IsSensitive, c.EnumValues)).ToList(),
            t.Uniques.Select(u => u.Name).ToList(),
            t.Checks.Select(c => c.Name).ToList(),
            t.Exclusions.Select(e => e.Name).ToList(),
            t.ForeignKeys.Select(f => new ExpectedForeignKey(f.Name, f.Columns, f.TargetTable, f.TargetColumns)).ToList(),
            t.Indexes.Select(i => i.Name).ToList(),
            (t.IsAppendOnly ? [$"tg_{t.Name}_append_only", $"tg_{t.Name}_no_truncate"] : new List<string>())
                .Concat(model.ImplementedStubs.SelectMany(st => st.Implementation!.Triggers).Where(tr => tr.Table == t.FullName).Select(tr => tr.Trigger))
                .ToList(),
            t.AppendOnlyUpdatable,
            CSharpEmitter.HasApi(model, t))).ToList();
        var stubs = model.Stubs.Select(s => new ExpectedStub(s.Table[..s.Table.IndexOf('.', StringComparison.Ordinal)], s.FunctionName, s.Table, s.Owner, s.Rule)).ToList();
        var catalog = new ExpectedCatalog($"{OutputSet.Marker} by tools/Erp.CodeGen from docs/data-design/*.yaml; do not edit", model.Settings.Release, tables, stubs);
        output.Add(CatalogPath, JsonSerializer.Serialize(catalog, ExpectedCatalog.JsonOptions) + "\n");
        output.Add(RegisterPath, Register(model));
    }

    /// <summary>The type as PostgreSQL's format_type() prints it.</summary>
    public static string FormatType(Column c) => c.Kind switch
    {
        ColumnKind.Timestamp => "timestamp with time zone",
        ColumnKind.Time => "time without time zone",
        ColumnKind.FixedText => "character" + c.SqlType["char".Length..],
        _ => c.SqlType,
    };

    private static string Register(DesignModel model)
    {
        var b = new StringBuilder();
        b.Append("<!-- <auto-generated> Generated by tools/Erp.CodeGen from tools/Erp.CodeGen/rules.yaml (slice S1.02). Do not edit by hand. </auto-generated> -->\n");
        b.Append("# Placeholder register (rules not enforced yet)\n\n");
        b.Append("Rules that the data design states only in words (table notes and checks) and that need a trigger or application\n");
        b.Append("logic. Each has a placeholder function in the database that enforces nothing and raises \"not implemented\" if called.\n");
        b.Append("The owning slice implements the rule, marks the entry implemented in `tools/Erp.CodeGen/rules.yaml` and regenerates.\n");
        b.Append("Tests fail if the database and this register disagree, or if an owning slice has a handoff note while its placeholder remains.\n\n");
        b.Append("| Owner | Table | Placeholder | Rule (design text) |\n| --- | --- | --- | --- |\n");
        foreach (var stub in model.Stubs.OrderBy(s => s.Owner, StringComparer.Ordinal).ThenBy(s => s.Table, StringComparer.Ordinal).ThenBy(s => s.Name, StringComparer.Ordinal))
        {
            var schema = stub.Table[..stub.Table.IndexOf('.', StringComparison.Ordinal)];
            b.Append(CultureInfo.InvariantCulture, $"| {stub.Owner} | {stub.Table} | `{schema}.{stub.FunctionName}()` | {stub.Rule.Replace("|", "\\|", StringComparison.Ordinal)} |\n");
        }

        b.Append(Naming.Invariant($"\n{model.Stubs.Count()} placeholders.\n"));
        return b.ToString();
    }
}
