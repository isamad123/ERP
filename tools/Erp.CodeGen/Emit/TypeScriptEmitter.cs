using System.Text.Json;
using System.Text.Json.Nodes;
using Erp.CodeGen.Design;
using N = Erp.CodeGen.Emit.CSharpNames;

namespace Erp.CodeGen.Emit;

/// <summary>
/// TypeScript types and a fetch client for every generated endpoint (web/generated/api), and JSON metadata for the
/// schema-driven list and form screens (web/generated/metadata) that S1.12's screen engine reads. Field names are
/// camelCase, matching ASP.NET Core's JSON output. Labels are localization keys, never display text.
/// </summary>
public static class TypeScriptEmitter
{
    public const string Root = "web/generated";

    private const string Header = "// <auto-generated>\n// Generated by tools/Erp.CodeGen from docs/data-design/*.yaml (slice S1.02). Do not edit by hand.\n// </auto-generated>\n";

    private static readonly string[] AuditColumns = ["created_at", "created_by", "updated_at", "updated_by", "row_version", "is_deleted", "deleted_at", "deleted_by"];

    public static void Emit(DesignModel model, OutputSet output)
    {
        output.Add($"{Root}/api/http.ts", Http());
        output.Add($"{Root}/tsconfig.json", TsConfig());
        var apiTables = model.Tables.Where(t => CSharpEmitter.HasApi(model, t)).ToList();
        foreach (var schema in apiTables.GroupBy(t => t.Schema).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            output.Add($"{Root}/api/{schema.Key}.ts", SchemaClient(schema.Key, schema.OrderBy(t => t.Name, StringComparer.Ordinal).ToList()));
        }

        output.Add($"{Root}/api/index.ts", Header + string.Concat(apiTables.Select(t => t.Schema).Distinct().Order(StringComparer.Ordinal).Select(s => $"export * as {s} from './{s}';\n")) + "export * from './http';\n");
        foreach (var table in apiTables)
        {
            output.Add($"{Root}/metadata/{table.FullName}.json", Metadata(table, model));
            output.Add($"{Root}/validation/{table.FullName}.json", ValidationSchema(table));
        }

        // English labels of every table and column (S1.12c Build item 15, ruling Q11); Urdu labels are kept by hand per
        // module (web/packages/i18n/labels), tenant overrides come from cfg.labels at run time.
        foreach (var module in model.Tables.Where(t => t.Database == DatabaseKind.Tenant).GroupBy(t => t.Module).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            output.Add($"{Root}/labels/{module.Key}.en.json", Labels(module.Where(t => CSharpEmitter.HasApi(model, t)).ToList()));
        }
    }

    private static readonly JsonSerializerOptions Indented = new() { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    /// <summary>"company_id" → "Company", "name_i18n" → "Name", "is_active" → "Active", "valid_from" → "Valid from".</summary>
    public static string EnglishLabel(string name)
    {
        var words = name.Split('_', StringSplitOptions.RemoveEmptyEntries).ToList();
        if (words.Count > 1 && words[^1] is "id" or "i18n" or "hmac")
        {
            words.RemoveAt(words.Count - 1);
        }

        if (words.Count > 1 && words[0] is "is" or "has")
        {
            words.RemoveAt(0);
        }

        var text = string.Join(' ', words.Select(w => w switch
        {
            "id" => "ID",
            "url" => "URL",
            "iban" => "IBAN",
            "ntn" => "NTN",
            "cnic" => "CNIC",
            "ip" => "IP",
            "mfa" => "MFA",
            _ => w,
        }));
        return text.Length == 0 ? name : char.ToUpperInvariant(text[0]) + text[1..];
    }

    /// <summary>"org.branches" → ("Branches", "Branch"), from the table name and the entity name.</summary>
    private static (string Many, string One) EntityLabels(Table t)
    {
        var many = EnglishLabel(t.Name);
        var one = EnglishLabel(string.Concat(N.Entity(t).Select((ch, i) => i > 0 && char.IsUpper(ch) ? "_" + char.ToLowerInvariant(ch) : char.ToLowerInvariant(ch).ToString())));
        return (many, one);
    }

    private static string Labels(IReadOnlyList<Table> tables)
    {
        var labels = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var t in tables)
        {
            var (many, one) = EntityLabels(t);
            labels[$"entities.{t.FullName}"] = many;
            labels[$"entities.{t.FullName}.one"] = one;
            foreach (var c in CSharpEmitter.ResponseColumns(t))
            {
                labels[$"fields.{t.FullName}.{c.Name}"] = EnglishLabel(c.Name);
                foreach (var v in c.EnumValues)
                {
                    labels[$"options.{t.FullName}.{c.Name}.{v}"] = EnglishLabel(v);
                }
            }
        }

        var root = new JsonObject { ["_generated"] = $"{OutputSet.Marker} by tools/Erp.CodeGen from docs/data-design/*.yaml; do not edit" };
        foreach (var (key, text) in labels)
        {
            root[key] = text;
        }

        return root.ToJsonString(Indented) + "\n";
    }

    /// <summary>
    /// The constraint names the database may report for a table (unique keys, checks, foreign keys) and the API field each
    /// one is about, so the form shows a refused save next to the field (S1.12c Build item 18). Constraints that span several
    /// fields (other than the company) are left out: the form shows those in its summary.
    /// </summary>
    private static JsonObject ConstraintFields(Table t, DesignModel model)
    {
        var map = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var columns = CSharpEmitter.ResponseColumns(t).Select(c => c.Name).ToHashSet(StringComparer.Ordinal);
        void Add(string name, IEnumerable<string> mentioned)
        {
            var fields = mentioned.Select(m => m.StartsWith("lower(", StringComparison.Ordinal) ? m[6..^1] : m)
                .Where(columns.Contains).Distinct(StringComparer.Ordinal).ToList();
            if (fields.Count > 1)
            {
                fields.Remove("company_id");
            }

            if (fields.Count == 1)
            {
                map[name] = Naming.Camel(fields[0]);
            }
        }

        foreach (var u in t.Uniques)
        {
            Add(u.Name, u.Items);
        }

        foreach (var f in t.ForeignKeys)
        {
            Add(f.Name, f.Columns);
        }

        foreach (var c in t.Checks)
        {
            Add(c.Name, columns.Where(col => System.Text.RegularExpressions.Regex.IsMatch(c.Sql, $@"\b{col}\b")));
        }

        // Constraints a trigger raises (rules.yaml functions, constraint_fields; S1.14a).
        foreach (var (table, constraint, column) in model.Functions.SelectMany(f => f.ConstraintFields).Where(c => c.Table == t.FullName))
        {
            Add(constraint, [column]);
        }

        return new JsonObject(map.Select(kv => KeyValuePair.Create(kv.Key, (JsonNode?)kv.Value)));
    }

    /// <summary>
    /// The validation schema of a table's create and update body (S1.12c Build item 14, ruling Q11): a JSON Schema
    /// (2020-12 subset) with the rules the server and the database check (required, code length and spacing, enum values,
    /// decimal digits), so the web form and the server cannot drift. A required two-language name needs at least one
    /// language filled (minProperties).
    /// </summary>
    private static string ValidationSchema(Table t)
    {
        var properties = new JsonObject();
        var required = new JsonArray();
        foreach (var c in CSharpEmitter.WritableColumns(t, update: false))
        {
            var p = SchemaOf(c);
            if (c.Required && c.Default is null && c.Kind is not (ColumnKind.TextArray or ColumnKind.UuidArray))
            {
                required.Add(Naming.Camel(c.Name));
            }
            else if (!c.Required)
            {
                p["nullable"] = true;
            }

            properties[Naming.Camel(c.Name)] = p;
        }

        var root = new JsonObject
        {
            ["_generated"] = $"{OutputSet.Marker} by tools/Erp.CodeGen from docs/data-design/*.yaml; do not edit",
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["title"] = t.FullName,
            ["type"] = "object",
            ["required"] = required,
            ["properties"] = properties,
        };
        return root.ToJsonString(Indented) + "\n";
    }

    private static JsonObject SchemaOf(Column c)
    {
        static JsonObject Str(string? format = null) => format is null ? new JsonObject { ["type"] = "string" } : new JsonObject { ["type"] = "string", ["format"] = format };
        switch (c.Kind)
        {
            case ColumnKind.Code:
                // The database check: length 1 to 40 and no leading or trailing spaces (ck_<table>_<column>_code).
                return new JsonObject { ["type"] = "string", ["minLength"] = 1, ["maxLength"] = 40, ["pattern"] = "^[^ ](.*[^ ])?$" };
            case ColumnKind.Enum:
                return new JsonObject { ["type"] = "string", ["enum"] = new JsonArray(c.EnumValues.Select(v => (JsonNode)v).ToArray()) };
            case ColumnKind.FixedText when System.Text.RegularExpressions.Regex.Match(c.SqlType, @"\((\d+)\)") is { Success: true } m:
                return new JsonObject { ["type"] = "string", ["minLength"] = 1, ["maxLength"] = int.Parse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture) };
            case ColumnKind.I18n:
                var i18n = new JsonObject
                {
                    ["type"] = "object",
                    ["propertyNames"] = new JsonObject { ["enum"] = new JsonArray(CSharpEmitter.SearchLanguages.Select(l => (JsonNode)l).ToArray()) },
                    ["additionalProperties"] = new JsonObject { ["type"] = "string", ["minLength"] = 1 },
                };
                if (c.Required)
                {
                    i18n["minProperties"] = 1;
                }

                return i18n;
            case ColumnKind.Uuid:
                return Str("uuid");
            case ColumnKind.Date:
                return Str("date");
            case ColumnKind.Timestamp:
                return Str("date-time");
            case ColumnKind.Time:
                return Str("time");
            case ColumnKind.Int4:
                return new JsonObject { ["type"] = "integer", ["minimum"] = int.MinValue, ["maximum"] = int.MaxValue };
            case ColumnKind.BigInteger:
                return new JsonObject { ["type"] = "integer" };
            case ColumnKind.Money or ColumnKind.Qty or ColumnKind.Rate or ColumnKind.Pct or ColumnKind.Numeric:
                // Exact decimals: the form keeps the digits as text (never a floating-point number), checked against the
                // column's precision and scale.
                var (precision, scale) = Precision(c.SqlType);
                return new JsonObject { ["type"] = "string", ["format"] = "decimal", ["pattern"] = $"^-?\\d{{1,{precision - scale}}}{(scale > 0 ? $"(\\.\\d{{1,{scale}}})?" : string.Empty)}$" };
            case ColumnKind.Bool:
                return new JsonObject { ["type"] = "boolean" };
            case ColumnKind.TextArray:
                return new JsonObject { ["type"] = "array", ["items"] = Str() };
            case ColumnKind.UuidArray:
                return new JsonObject { ["type"] = "array", ["items"] = Str("uuid") };
            case ColumnKind.Json:
                return new JsonObject { ["readOnly"] = true };
            default:
                return Str();
        }
    }

    private static (int Precision, int Scale) Precision(string sqlType)
    {
        var m = System.Text.RegularExpressions.Regex.Match(sqlType, @"\((\d+)\s*,\s*(\d+)\)");
        return m.Success
            ? (int.Parse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture), int.Parse(m.Groups[2].Value, System.Globalization.CultureInfo.InvariantCulture))
            : (19, 4);
    }

    private static string TsConfig() =>
        "// <auto-generated> Generated by tools/Erp.CodeGen (slice S1.02); used by CI to type-check the generated client. </auto-generated>\n" +
        "{\n  \"compilerOptions\": {\n    \"target\": \"ES2022\",\n    \"module\": \"ES2022\",\n    \"moduleResolution\": \"Bundler\",\n    \"lib\": [\"ES2022\", \"DOM\"],\n" +
        "    \"strict\": true,\n    \"noEmit\": true,\n    \"skipLibCheck\": true,\n    \"resolveJsonModule\": true\n  },\n  \"include\": [\"api/**/*.ts\"]\n}\n";

    private static string Http() => Header + """

        /** One keyset page; pass `next` back as `after` to read the next page. */
        export interface PagedResult<T> {
          items: T[];
          next: string | null;
        }

        /** RFC 9457 problem details returned by the API. `title` is a localization key such as `errors.data.not_found`. */
        export interface Problem {
          status: number;
          title: string;
          detail?: string | null;
          errors?: Record<string, string[]>;
        }

        export class ApiError extends Error {
          constructor(public readonly problem: Problem) {
            super(problem.title);
          }
        }

        export interface HttpOptions {
          query?: object;
          body?: unknown;
        }

        export type Fetcher = (input: string, init: RequestInit) => Promise<Response>;

        let baseUrl = '';
        let fetcher: Fetcher = (input, init) => fetch(input, init);

        /** Sets the API base URL and, optionally, the fetch function (for authentication headers or tests). */
        export function configureApi(url: string, customFetch?: Fetcher): void {
          baseUrl = url.replace(/\/$/, '');
          if (customFetch) {
            fetcher = customFetch;
          }
        }

        export async function request<T>(method: string, path: string, options: HttpOptions = {}): Promise<T> {
          const params = new URLSearchParams();
          for (const [key, value] of Object.entries(options.query ?? {})) {
            if (value !== undefined && value !== null) {
              params.set(key, String(value));
            }
          }
          const query = params.toString();
          const response = await fetcher(baseUrl + path + (query ? '?' + query : ''), {
            method,
            headers: options.body === undefined ? undefined : { 'Content-Type': 'application/json' },
            body: options.body === undefined ? undefined : JSON.stringify(options.body),
          });
          if (!response.ok) {
            const problem = (await response.json().catch(() => ({ status: response.status, title: 'errors.http.' + response.status }))) as Problem;
            throw new ApiError(problem);
          }
          return response.status === 204 ? (undefined as T) : ((await response.json()) as T);
        }

        """.Replace("\r", string.Empty, StringComparison.Ordinal);

    private static string SchemaClient(string schema, IReadOnlyList<Table> tables)
    {
        var w = new CodeWriter();
        w.Line(Header.TrimEnd('\n')).Line("import { request, type PagedResult } from './http';").Line();
        foreach (var t in tables)
        {
            var entity = N.Entity(t);
            w.Line($"/** {t.FullName}: {(t.Purpose ?? entity).Replace("*/", "* /", StringComparison.Ordinal)}. Field rules (S1.06) may leave a field out or mask it as text. */");
            w.Open($"export interface {entity}");
            foreach (var c in CSharpEmitter.ResponseColumns(t))
            {
                // Salary fields are hidden unless a field rule opens them, and may be masked ("****1234"), GHR-06.
                var salary = c.FieldClass == "salary";
                w.Line($"{Naming.Camel(c.Name)}{(salary ? "?" : string.Empty)}: {N.TsType(c)}{(salary ? " | string" : string.Empty)}{(c.Required ? string.Empty : " | null")};");
            }

            w.Close().Line();
            if (CSharpEmitter.CanWrite(t))
            {
                w.Open($"export interface {entity}Write");
                foreach (var c in CSharpEmitter.WritableColumns(t, update: false))
                {
                    var optional = !c.Required || c.Default is not null || c.Kind is ColumnKind.TextArray or ColumnKind.UuidArray;
                    w.Line($"{Naming.Camel(c.Name)}{(optional ? "?" : string.Empty)}: {N.TsType(c)}{(c.Required ? string.Empty : " | null")};");
                }

                w.Close().Line();
            }

            w.Open($"export interface {entity}ListQuery");
            w.Line("after?: string;");
            w.Line("limit?: number;");
            foreach (var c in CSharpEmitter.FilterColumns(t))
            {
                w.Line($"{Naming.Camel(c.Name)}?: {N.TsType(c)};");
            }

            if (CSharpEmitter.SortColumns(t) is { Count: > 0 } sorts)
            {
                w.Line($"/** {string.Join(", ", sorts.Select(x => Naming.Camel(x.Column.Name)))}; a leading minus sorts descending. */");
                w.Line($"sort?: {string.Join(" | ", sorts.SelectMany(x => new[] { $"'{Naming.Camel(x.Column.Name)}'", $"'-{Naming.Camel(x.Column.Name)}'" }))};");
            }

            if (CSharpEmitter.SearchColumns(t).Count > 0)
            {
                w.Line("search?: string;");
            }

            w.Close().Line();
            var route = N.Route(t);
            w.Open($"export const {Naming.Camel(t.Name)} =");
            w.Line($"list: (query: {entity}ListQuery = {{}}) => request<PagedResult<{entity}>>('GET', '{route}', {{ query }}),");
            w.Line($"get: (id: string) => request<{entity}>('GET', `{route}/${{id}}`),");
            if (CSharpEmitter.CanCreate(t))
            {
                w.Line($"create: (body: {entity}Write) => request<{entity}>('POST', '{route}', {{ body }}),");
            }

            if (CSharpEmitter.CanUpdate(t))
            {
                w.Line($"update: (id: string, body: {entity}Write & {{ rowVersion: number }}) => request<{entity}>('PUT', `{route}/${{id}}`, {{ body }}),");
            }

            if (CSharpEmitter.CanDelete(t))
            {
                w.Line($"remove: (id: string, rowVersion: number) => request<void>('DELETE', `{route}/${{id}}`, {{ query: {{ rowVersion }} }}),");
            }

            w.Close(";").Line();
        }

        return w.ToString().TrimEnd('\n') + "\n";
    }

    private static string Metadata(Table t, DesignModel model)
    {
        var filters = CSharpEmitter.FilterColumns(t).Select(c => c.Name).ToHashSet(StringComparer.Ordinal);
        var writable = CSharpEmitter.WritableColumns(t, update: false).Select(c => c.Name).ToHashSet(StringComparer.Ordinal);
        var references = t.ForeignKeys.Where(f => f.Columns.Count >= 1).SelectMany(f => f.Columns.Zip(f.TargetColumns, (c, tc) => (c, f.TargetTable, tc)))
            .Where(x => x.c != "company_id" || t.ForeignKeys.Exists(f => f.Columns.SequenceEqual(["company_id"])))
            .GroupBy(x => x.c).ToDictionary(g => g.Key, g => g.First().TargetTable, StringComparer.Ordinal);

        var sortable = CSharpEmitter.SortColumns(t).Select(x => x.Column.Name).ToHashSet(StringComparer.Ordinal);
        var fields = new JsonArray();
        foreach (var c in CSharpEmitter.ResponseColumns(t))
        {
            var field = new JsonObject
            {
                ["column"] = c.Name,
                ["field"] = Naming.Camel(c.Name),
                ["kind"] = c.Kind.ToString(),
                ["required"] = c.Required,
                ["readOnly"] = !writable.Contains(c.Name),
                ["system"] = AuditColumns.Contains(c.Name) || c.Name == "id",
                ["filter"] = filters.Contains(c.Name),
                ["labelKey"] = $"fields.{t.FullName}.{c.Name}",
            };
            if (c.FieldClass is not null)
            {
                field["fieldClass"] = c.FieldClass;
            }

            if (c.ApiCreateOnly)
            {
                field["createOnly"] = true; // set on create only (CR-062): the screen shows it read-only when editing
            }
            if (c.EnumValues.Count > 0)
            {
                field["options"] = new JsonArray(c.EnumValues.Select(v => (JsonNode)new JsonObject { ["value"] = v, ["labelKey"] = $"options.{t.FullName}.{c.Name}.{v}" }).ToArray());
            }

            if (c.Kind is ColumnKind.Code)
            {
                field["maxLength"] = 40;
            }

            if (references.TryGetValue(c.Name, out var target))
            {
                field["references"] = target;
            }

            if (sortable.Contains(c.Name))
            {
                field["sortable"] = true;
            }

            fields.Add(field);
        }

        var listFields = CSharpEmitter.ResponseColumns(t)
            .Where(c => !AuditColumns.Contains(c.Name) && c.Name is not ("id" or "custom") && c.Kind is not (ColumnKind.Json or ColumnKind.TextArray or ColumnKind.UuidArray or ColumnKind.Bytea))
            .Take(8)
            .Select(c => (JsonNode)Naming.Camel(c.Name))
            .ToArray();

        var root = new JsonObject
        {
            ["_generated"] = $"{OutputSet.Marker} by tools/Erp.CodeGen from docs/data-design/*.yaml; do not edit",
            ["table"] = t.FullName,
            ["resource"] = N.Resource(t),
            ["route"] = N.Route(t),
            ["labelKey"] = $"entities.{t.FullName}",
            ["requirements"] = new JsonArray(t.Requirements.Select(r => (JsonNode)r).ToArray()),
            ["actions"] = new JsonArray(CSharpEmitter.Actions(t).Select(a => (JsonNode)new JsonObject { ["action"] = a, ["permission"] = N.Permission(t, a) }).ToArray()),
            ["companyScoped"] = t.IsCompanyScoped,
            ["effectiveDated"] = t.IsEffectiveDated,
            ["softDelete"] = t.IsSoftDeleted,
            ["appendOnly"] = t.IsAppendOnly,
            ["scope"] = new JsonObject(t.ScopeLocators.Select(kv => KeyValuePair.Create(kv.Key, (JsonNode?)Naming.Camel(kv.Value)))
                .Concat(t.ScopeVia is { } via ? [KeyValuePair.Create("via", (JsonNode?)Naming.Camel(via))] : [])),
            ["listFields"] = new JsonArray(listFields),
            ["search"] = new JsonArray(CSharpEmitter.SearchColumns(t).Select(c => (JsonNode)Naming.Camel(c.Name)).ToArray()),
            ["constraints"] = ConstraintFields(t, model),
            ["fields"] = fields,
        };
        return root.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }) + "\n";
    }
}
