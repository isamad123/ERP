using Erp.CodeGen.Design;
using N = Erp.CodeGen.Emit.CSharpNames;

namespace Erp.CodeGen.Emit;

/// <summary>
/// Entities (Domain), repository interfaces and filters (Application), EF Core configuration, DbContext and
/// repositories (Infrastructure), minimal API endpoints (Api) and the permission catalogue (Contracts).
/// Entities sit in Domain rather than Infrastructure because the layer rules (spec 01 section 4.3) let Application
/// and Api see Domain but not Infrastructure; the EF Core mapping stays in Infrastructure.
/// </summary>
public static class CSharpEmitter
{
    private const string Header =
        "// <auto-generated>\n" +
        "// Generated by tools/Erp.CodeGen from docs/data-design/*.yaml (slice S1.02). Do not edit by hand.\n" +
        "// Add behaviour in a separate partial class file, or change the design and re-run the generator.\n" +
        "// </auto-generated>\n" +
        "#nullable enable\n";

    private static readonly string[] AuditColumns = ["id", "created_at", "created_by", "updated_at", "updated_by", "row_version", "is_deleted", "deleted_at", "deleted_by"];

    public static bool HasRepository(Table t) => t.HasIdKey && !t.IsOutboxOrInbox;

    public static bool HasApi(DesignModel model, Table t) =>
        HasRepository(t) && t.Database == DatabaseKind.Tenant && !model.Settings.ApiExcluded.Contains(t.FullName);

    /// <summary>Create and update endpoints need every required column; encrypted values need the key service (S1.06/S1.07).</summary>
    private static bool Writable(Table t) => !t.Columns.Exists(c => c.IsSensitive && c.Required);

    public static bool CanCreate(Table t) => Writable(t) && t.AllowsApi("create");

    public static bool CanUpdate(Table t) => Writable(t) && t.HasRowVersion && !t.IsAppendOnly && t.AllowsApi("update");

    /// <summary>True when the generated API accepts a body (create or update); data-design key api_actions may close both.</summary>
    public static bool CanWrite(Table t) => CanCreate(t) || CanUpdate(t);

    public static bool CanDelete(Table t) => t.IsSoftDeleted && t.HasRowVersion && t.AllowsApi("delete");

    /// <summary>
    /// Actions with a permission code: the generated API's, plus create and update for a table whose encrypted columns a
    /// hand-written service writes and shows (design key field_view, S1.14a): the generated API cannot write them.
    /// </summary>
    public static IEnumerable<string> PermissionActions(Table t)
    {
        var generated = Actions(t).ToList();
        if (t.Columns.Exists(c => c.InFieldCatalogue))
        {
            void Add(string action)
            {
                if (!generated.Contains(action, StringComparer.Ordinal))
                {
                    generated.Add(action);
                }
            }

            Add("create");
            if (t.HasRowVersion)
            {
                Add("update");
                if (t.IsSoftDeleted)
                {
                    Add("delete");
                }
            }
        }

        return generated;
    }

    public static IEnumerable<string> Actions(Table t)
    {
        yield return "read";
        if (CanCreate(t))
        {
            yield return "create";
        }

        if (CanUpdate(t))
        {
            yield return "update";
        }

        if (CanDelete(t))
        {
            yield return "delete";
        }
    }

    public static IReadOnlyList<Column> WritableColumns(Table t, bool update) =>
        t.Columns.Where(c => !AuditColumns.Contains(c.Name) && !c.IsGenerated && !c.IsSensitive && !c.ApiReadOnly && !(update && c.Name == "company_id")).ToList();

    public static IReadOnlyList<Column> ResponseColumns(Table t) => t.Columns.Where(c => !c.IsSensitive).ToList();

    /// <summary>Equality filters on list endpoints: foreign-key columns, status and (S1.12c, the list engine's "Active" filter) is_active.</summary>
    public static IReadOnlyList<Column> FilterColumns(Table t)
    {
        var names = t.ForeignKeys.SelectMany(f => f.Columns).Append("status").Append("is_active").ToHashSet(StringComparer.Ordinal);
        return t.Columns.Where(c => names.Contains(c.Name) && c.Kind is not (ColumnKind.Json or ColumnKind.I18n or ColumnKind.TextArray or ColumnKind.UuidArray or ColumnKind.Bytea)).ToList();
    }

    private static readonly ColumnKind[] SortableKinds =
    [
        ColumnKind.Code, ColumnKind.Text, ColumnKind.Enum, ColumnKind.FixedText, ColumnKind.Date, ColumnKind.Timestamp, ColumnKind.Time,
        ColumnKind.Int4, ColumnKind.BigInteger, ColumnKind.Money, ColumnKind.Qty, ColumnKind.Rate, ColumnKind.Pct, ColumnKind.Numeric,
    ];

    /// <summary>Languages a name is searched in (Release 1.0: English and Urdu, D-42).</summary>
    public static readonly string[] SearchLanguages = ["en", "ur"];

    /// <summary>
    /// Sort keys of the list endpoint (slice S1.12c Build item 14, ruling Q11): required columns the data design indexes (an
    /// item of a unique key or index), so a sorted page comes from an index. Codes and text indexed as <c>lower(column)</c>
    /// sort without case. Ids and references are left out (their order means nothing to a reader); so are optional columns
    /// (keyset paging needs a value on every row) and booleans.
    /// </summary>
    public static IReadOnlyList<(Column Column, bool Lower)> SortColumns(Table t)
    {
        var items = t.Uniques.SelectMany(u => u.Items).Concat(t.Indexes.SelectMany(i => i.Items)).ToHashSet(StringComparer.Ordinal);
        return t.Columns
            .Where(c => c.Required && c.OptionalIn is null && !c.IsSensitive && !c.IsGenerated && c.Name != "id" && SortableKinds.Contains(c.Kind))
            .Where(c => items.Contains(c.Name) || items.Contains($"lower({c.Name})"))
            .Select(c => (c, items.Contains($"lower({c.Name})") && c.Kind is ColumnKind.Code or ColumnKind.Text))
            .ToList();
    }

    /// <summary>Columns the list search looks in (Build item 14): the code and the name (plain text or every language of a two-language name).</summary>
    public static IReadOnlyList<Column> SearchColumns(Table t) =>
        t.Columns.Where(c => (c.Name == "code" && c.Kind is ColumnKind.Code or ColumnKind.Text)
            || (c.Name == "name" && c.Kind is ColumnKind.Text)
            || (c.Name == "name_i18n" && c.Kind is ColumnKind.I18n)).ToList();

    /// <summary><c>Sort</c> and <c>Search</c> of a list query or filter, for tables that have sort keys or search columns.</summary>
    private static void ListOptionProperties(CodeWriter w, Table t, bool filter)
    {
        if (SortColumns(t) is { Count: > 0 } sorts)
        {
            if (!filter)
            {
                w.Line();
            }

            w.Line($"/// <summary>Sort key: {CodeWriter.Xml(string.Join(", ", sorts.Select(s => Naming.Camel(s.Column.Name))))}; a leading minus sorts descending. Empty: by id (creation order).</summary>");
            w.Line("public string? Sort { get; init; }");
        }

        if (SearchColumns(t) is { Count: > 0 } search)
        {
            if (!filter)
            {
                w.Line();
            }

            w.Line($"/// <summary>Case-insensitive text found in {CodeWriter.Xml(string.Join(", ", search.Select(c => Naming.Camel(c.Name))))}.</summary>");
            w.Line("public string? Search { get; init; }");
        }

        if (t.IsEffectiveDated)
        {
            if (!filter)
            {
                w.Line();
            }

            // S1.20b (GHR-03, FR-HRM-EMP-11): every effective-dated list answers as of a date.
            w.Line("/// <summary>Only the rows valid on this date (valid_from on or before it, valid_to after it or open).</summary>");
            w.Line("public global::System.DateOnly? AsOf { get; init; }");
        }
    }

    public static void Emit(DesignModel model, OutputSet output)
    {
        foreach (var table in model.Tables)
        {
            output.Add($"{N.Folder(table, "Domain")}/{N.Entity(table)}.g.cs", Entity(table));
            output.Add($"{N.Folder(table, "Infrastructure")}/{N.Entity(table)}Persistence.g.cs", Persistence(table));
            if (HasRepository(table))
            {
                output.Add($"{N.Folder(table, "Application")}/{N.RepositoryInterface(table)}.g.cs", RepositoryInterface(table));
            }

            if (HasApi(model, table))
            {
                output.Add($"{N.Folder(table, "Api")}/{N.Entity(table)}Endpoints.g.cs", Endpoints(table));
            }
        }

        foreach (var module in model.Tables.GroupBy(t => t.Module))
        {
            var tables = module.OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
            var sample = tables[0];
            var infraRoot = module.Key == "controlplane" ? "src/Platform/Erp.Kernel.Infrastructure/ControlPlane/Generated" : $"{N.ModuleFolder(sample)}/Erp.{N.ModuleProject(sample)}.Infrastructure/Generated";
            output.Add($"{infraRoot}/{N.DbContextName(sample)}.g.cs", DbContext(module.Key, tables));
            if (module.Key != "controlplane")
            {
                output.Add($"{infraRoot}/{N.ModuleProject(sample)}ResourceCatalog.g.cs", ResourceCatalog(module.Key, tables.Where(HasRepository).ToList()));
                output.Add($"{infraRoot}/{N.ModuleProject(sample)}AuditCatalog.g.cs", AuditCatalog(module.Key, tables));
            }
            if (module.Key == "controlplane")
            {
                continue;
            }

            var apiTables = tables.Where(t => HasApi(model, t)).ToList();
            var project = N.ModuleProject(sample);
            output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Api/Generated/{project}GeneratedEndpoints.g.cs", EndpointRoot(project, apiTables));
            output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Contracts/Generated/{project}Permissions.g.cs", Permissions(project, apiTables));
            output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Infrastructure/Access/permissions.g.json", PermissionManifest(module.Key, apiTables));
            var numbered = tables.Where(t => t.Numbering.Count > 0).ToList();
            if (numbered.Count > 0)
            {
                output.Add($"{infraRoot}/{project}NumberingTypes.g.cs", NumberingTypes(project, numbered));
                output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Infrastructure/Access/numbering.g.json", NumberingManifest(module.Key, numbered));
            }
        }
    }

