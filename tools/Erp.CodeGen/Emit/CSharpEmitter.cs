    private static string RepositoryInterface(Table t)
    {
        var e = N.EntityFull(t);
        var baseInterface = t.IsSoftDeleted && t.HasRowVersion ? "ISoftDeleteRepository"
            : t.HasRowVersion ? "IMutableRepository"
            : "IRepository";
        var w = new CodeWriter();
        w.Line(Header).Line($"namespace {N.Namespace(t, "Application")};").Line();
        w.Line($"/// <summary>Equality filters for listing {CodeWriter.Xml(t.FullName)} (foreign keys and status). Null means no filter.</summary>");
        w.Open($"public sealed record {N.Filter(t)}");
        foreach (var c in FilterColumns(t))
        {
            var (type, _) = N.BaseType(c);
            w.Line($"public {type}? {N.Property(t, c)} {{ get; init; }}");
        }

        w.Close().Line();
        w.Line($"/// <summary>Generated repository of {CodeWriter.Xml(t.FullName)}.</summary>");
        w.Open($"public interface {N.RepositoryInterface(t)} : global::Erp.BuildingBlocks.Application.Data.{baseInterface}<{e}>");
        w.Line($"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> ListAsync({N.Filter(t)} filter, global::Erp.BuildingBlocks.Application.Data.PageRequest page, global::System.Threading.CancellationToken cancellationToken);");
        if (t.IsCompanyScoped)
        {
            w.Line();
            w.Line($"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> ListByCompanyAsync(global::System.Guid companyId, global::Erp.BuildingBlocks.Application.Data.PageRequest page, global::System.Threading.CancellationToken cancellationToken);");
        }

        foreach (var finder in Finders(t))
        {
            w.Line();
            w.Line($"/// <summary>Rows matching ({CodeWriter.Xml(string.Join(", ", finder.Items))}); at most PageRequest.MaxLimit rows.</summary>");
            w.Line($"global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> {finder.Name}({finder.Parameters}, global::System.Threading.CancellationToken cancellationToken);");
        }

        w.Close();
        return w.ToString();
    }

