    private static string Entity(Table t)
    {
        var w = new CodeWriter();
        w.Line(Header).Line($"namespace {N.Namespace(t, "Domain")};").Line();
        w.Line("/// <summary>");
        w.Line($"/// {CodeWriter.Xml(t.FullName + ": " + (t.Purpose ?? N.Entity(t)))}.");
        if (t.Requirements.Count > 0)
        {
            w.Line($"/// Requirements: {CodeWriter.Xml(string.Join(", ", t.Requirements))}.");
        }

        w.Line("/// </summary>");
        var interfaces = Interfaces(t);
        w.Open($"public sealed partial class {N.Entity(t)}{(interfaces.Count > 0 ? " : " + string.Join(", ", interfaces) : string.Empty)}");
        var first = true;
        foreach (var c in t.Columns)
        {
            if (!first)
            {
                w.Line();
            }

            first = false;
            var doc = c.Name + (c.Comment is null ? string.Empty : ": " + c.Comment) + (c.Kind is ColumnKind.Encrypted ? " (ciphertext; see IFieldEncryptor)" : string.Empty);
            w.Line($"/// <summary>{CodeWriter.Xml(doc)}</summary>");
            w.Line($"public {N.ClrType(c)} {N.Property(t, c)} {{ get; set; }}{Initializer(c)}");
        }

        w.Close();
        return w.ToString();
    }

    private static List<string> Interfaces(Table t)
    {
        const string ns = "global::Erp.BuildingBlocks.Domain.Entities.";
        var list = new List<string>();
        if (t.HasIdKey && t.Column("id").Kind is ColumnKind.Uuid)
        {
            list.Add(ns + "IEntity");
        }

        if (t.HasColumn("created_at") && t.HasColumn("created_by") && t.Traits.Count > 0)
        {
            list.Add(ns + "ICreationAudited");
        }

        if (t.Traits.Contains("std"))
        {
            list.Add(ns + "IVersioned");
        }

        if (t.IsSoftDeleted)
        {
            list.Add(ns + "ISoftDeletable");
        }

        // A company made optional later (optional_added_in, S1.08: tenant-wide numbering schemes) is not ICompanyScoped.
        if (t.IsCompanyScoped && t.Column("company_id").Required)
        {
            list.Add(ns + "ICompanyScoped");
        }

        if (t.IsAppendOnly)
        {
            list.Add(ns + "IAppendOnly");
        }

        return list;
    }

    private static string Initializer(Column c)
    {
        if (!c.Required)
        {
            return string.Empty;
        }

        if (c.Default is { } d)
        {
            switch (c.Kind)
            {
                case ColumnKind.Bool:
                    return d == "true" ? " = true;" : string.Empty;
                case ColumnKind.Enum when d.StartsWith('\''):
                    return $" = {CodeWriter.CSharpString(d.Trim('\''))};";
                case ColumnKind.Json:
                    return " = global::System.Text.Json.JsonDocument.Parse(\"{}\");";
                case ColumnKind.Int4 or ColumnKind.BigInteger:
                    return d == "0" ? string.Empty : $" = {d};";
                case ColumnKind.Money or ColumnKind.Qty or ColumnKind.Rate or ColumnKind.Pct or ColumnKind.Numeric:
                    return d == "0" ? string.Empty : $" = {d}m;";
                default:
                    break;
            }
        }

        return c.Kind switch
        {
            ColumnKind.TextArray or ColumnKind.UuidArray => " = [];",
            _ when !N.BaseType(c).IsValueType => " = null!;",
            _ => string.Empty,
        };
    }

