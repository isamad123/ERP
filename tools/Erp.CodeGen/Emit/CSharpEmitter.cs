            return c.Required ? "global::System.Text.Json.JsonElement" : "global::System.Text.Json.JsonElement?";
        }

        if (c.Kind is ColumnKind.Inet)
        {
            return "string?";
        }

        return N.ClrType(c);
    }

    private static string ResponseValue(Table t, Column c)
    {
        var p = "row." + N.Property(t, c);
        return c.Kind switch
        {
            ColumnKind.I18n or ColumnKind.Json => c.Required ? $"{p}.RootElement.Clone()" : $"{p}?.RootElement.Clone()",
            ColumnKind.Inet => $"{p}?.ToString()",
            _ => p,
        };
    }

    private static string RequestValue(Table t, Column c)
    {
        var p = "request." + N.Property(t, c);
        var (_, isValue) = N.BaseType(c);
        return c.Kind switch
        {
            ColumnKind.I18n or ColumnKind.Json => c.Required ? $"GeneratedEndpointSupport.ToDocument({p})!" : $"GeneratedEndpointSupport.ToDocument({p})",
            ColumnKind.Inet => $"{p} is null ? null : global::System.Net.IPAddress.Parse({p})",
            ColumnKind.TextArray or ColumnKind.UuidArray => c.Required ? $"{p} ?? []" : p,
            _ when c.Required && isValue => $"{p}!.Value",
            _ when c.Required => $"{p}!",
            _ => p,
        };
    }

