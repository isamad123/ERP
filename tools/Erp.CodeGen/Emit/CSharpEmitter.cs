using Erp.CodeGen.Design;
using N = Erp.CodeGen.Emit.CSharpNames;

namespace Erp.CodeGen.Emit;

/// <summary>
/// Entities (Domain), repository interfaces and filters (Application), EF Core configuration, DbContext and
/// repositories (Infrastructure), minimal API endpoints (Api) and the permission catalogue (Contracts).
/// Entities sit in Domain rather than Infrastructure because the layer rules (spec 01 section 4.3) let Application
/// and Api see Domain but not Infrastructure; the EF Core mapping stays in Infrastructure.
/// </summary>
public static class CSharpEmitter
{
    private const string Header =
        "// <auto-generated>\n" +
        "// Generated by tools/Erp.CodeGen from docs/data-design/*.yaml (slice S1.02). Do not edit by hand.\n" +
        "// Add behaviour in a separate partial class file, or change the design and re-run the generator.\n" +
        "// </auto-generated>\n" +
        "#nullable enable\n";

    private static readonly string[] AuditColumns = ["id", "created_at", "created_by", "updated_at", "updated_by", "row_version", "is_deleted", "deleted_at", "deleted_by"];

    public static bool HasRepository(Table t) => t.HasIdKey && !t.IsOutboxOrInbox;

    public static bool HasApi(DesignModel model, Table t) =>
        HasRepository(t) && t.Database == DatabaseKind.Tenant && !model.Settings.ApiExcluded.Contains(t.FullName);

    /// <summary>Create and update endpoints need every required column; encrypted values need the key service (S1.06/S1.07).</summary>
    public static bool CanWrite(Table t) => !t.Columns.Exists(c => c.IsSensitive && c.Required);

    public static bool CanUpdate(Table t) => CanWrite(t) && t.HasRowVersion && !t.IsAppendOnly;

    public static IEnumerable<string> Actions(Table t)
    {
        yield return "read";
        if (CanWrite(t))
        {
            yield return "create";
        }

        if (CanUpdate(t))
        {
            yield return "update";
        }

        if (t.IsSoftDeleted && t.HasRowVersion)
        {
            yield return "delete";
        }
    }

    public static IReadOnlyList<Column> WritableColumns(Table t, bool update) =>
        t.Columns.Where(c => !AuditColumns.Contains(c.Name) && !c.IsGenerated && !c.IsSensitive && !c.ApiReadOnly && !(update && c.Name == "company_id")).ToList();

    public static IReadOnlyList<Column> ResponseColumns(Table t) => t.Columns.Where(c => !c.IsSensitive).ToList();

    /// <summary>Equality filters on list endpoints: foreign-key columns and status.</summary>
    public static IReadOnlyList<Column> FilterColumns(Table t)
    {
        var names = t.ForeignKeys.SelectMany(f => f.Columns).Append("status").ToHashSet(StringComparer.Ordinal);
        return t.Columns.Where(c => names.Contains(c.Name) && c.Kind is not (ColumnKind.Json or ColumnKind.I18n or ColumnKind.TextArray or ColumnKind.UuidArray or ColumnKind.Bytea)).ToList();
    }

    public static void Emit(DesignModel model, OutputSet output)
    {
        foreach (var table in model.Tables)
        {
            output.Add($"{N.Folder(table, "Domain")}/{N.Entity(table)}.g.cs", Entity(table));
            output.Add($"{N.Folder(table, "Infrastructure")}/{N.Entity(table)}Persistence.g.cs", Persistence(table));
            if (HasRepository(table))
            {
                output.Add($"{N.Folder(table, "Application")}/{N.RepositoryInterface(table)}.g.cs", RepositoryInterface(table));
            }

            if (HasApi(model, table))
            {
                output.Add($"{N.Folder(table, "Api")}/{N.Entity(table)}Endpoints.g.cs", Endpoints(table));
            }
        }

        foreach (var module in model.Tables.GroupBy(t => t.Module))
        {
            var tables = module.OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
            var sample = tables[0];
            var infraRoot = module.Key == "controlplane" ? "src/Platform/Erp.Kernel.Infrastructure/ControlPlane/Generated" : $"{N.ModuleFolder(sample)}/Erp.{N.ModuleProject(sample)}.Infrastructure/Generated";
            output.Add($"{infraRoot}/{N.DbContextName(sample)}.g.cs", DbContext(module.Key, tables));
            if (module.Key == "controlplane")
            {
                continue;
            }

            var apiTables = tables.Where(t => HasApi(model, t)).ToList();
            var project = N.ModuleProject(sample);
            output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Api/Generated/{project}GeneratedEndpoints.g.cs", EndpointRoot(project, apiTables));
            output.Add($"{N.ModuleFolder(sample)}/Erp.{project}.Contracts/Generated/{project}Permissions.g.cs", Permissions(project, apiTables));
        }
    }

    // ---------------------------------------------------------------- Domain

    private static string Entity(Table t)
    {
        var w = new CodeWriter();
        w.Line(Header).Line($"namespace {N.Namespace(t, "Domain")};").Line();
        w.Line("/// <summary>");
        w.Line($"/// {CodeWriter.Xml(t.FullName + ": " + (t.Purpose ?? N.Entity(t)))}.");
        if (t.Requirements.Count > 0)
        {
            w.Line($"/// Requirements: {CodeWriter.Xml(string.Join(", ", t.Requirements))}.");
        }

        w.Line("/// </summary>");
        var interfaces = Interfaces(t);
        w.Open($"public sealed partial class {N.Entity(t)}{(interfaces.Count > 0 ? " : " + string.Join(", ", interfaces) : string.Empty)}");
        var first = true;
        foreach (var c in t.Columns)
        {
            if (!first)
            {
                w.Line();
            }

            first = false;
            var doc = c.Name + (c.Comment is null ? string.Empty : ": " + c.Comment) + (c.Kind is ColumnKind.Encrypted ? " (ciphertext; see IFieldEncryptor)" : string.Empty);
            w.Line($"/// <summary>{CodeWriter.Xml(doc)}</summary>");
            w.Line($"public {N.ClrType(c)} {N.Property(t, c)} {{ get; set; }}{Initializer(c)}");
        }

        w.Close();
        return w.ToString();
    }

    private static List<string> Interfaces(Table t)
    {
        const string ns = "global::Erp.BuildingBlocks.Domain.Entities.";
        var list = new List<string>();
        if (t.HasIdKey && t.Column("id").Kind is ColumnKind.Uuid)
        {
            list.Add(ns + "IEntity");
        }

        if (t.HasColumn("created_at") && t.HasColumn("created_by") && t.Traits.Count > 0)
        {
            list.Add(ns + "ICreationAudited");
        }

        if (t.Traits.Contains("std"))
        {
            list.Add(ns + "IVersioned");
        }

        if (t.IsSoftDeleted)
        {
            list.Add(ns + "ISoftDeletable");
        }

        if (t.IsCompanyScoped)
        {
            list.Add(ns + "ICompanyScoped");
        }

        if (t.IsAppendOnly)
        {
            list.Add(ns + "IAppendOnly");
        }

        return list;
    }

    private static string Initializer(Column c)
    {
        if (!c.Required)
        {
            return string.Empty;
        }

        if (c.Default is { } d)
        {
            switch (c.Kind)
            {
                case ColumnKind.Bool:
                    return d == "true" ? " = true;" : string.Empty;
                case ColumnKind.Enum when d.StartsWith('\''):
                    return $" = {CodeWriter.CSharpString(d.Trim('\''))};";
                case ColumnKind.Json:
                    return " = global::System.Text.Json.JsonDocument.Parse(\"{}\");";
                case ColumnKind.Int4 or ColumnKind.BigInteger:
                    return d == "0" ? string.Empty : $" = {d};";
                case ColumnKind.Money or ColumnKind.Qty or ColumnKind.Rate or ColumnKind.Pct or ColumnKind.Numeric:
                    return d == "0" ? string.Empty : $" = {d}m;";
                default:
                    break;
            }
        }

        return c.Kind switch
        {
            ColumnKind.TextArray or ColumnKind.UuidArray => " = [];",
            _ when !N.BaseType(c).IsValueType => " = null!;",
            _ => string.Empty,
        };
    }

