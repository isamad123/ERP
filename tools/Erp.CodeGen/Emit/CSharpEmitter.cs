    private static string ResponseType(Column c)
    {
        if (c.Kind is ColumnKind.I18n or ColumnKind.Json)
        {
            return c.Required ? "global::System.Text.Json.JsonElement" : "global::System.Text.Json.JsonElement?";
        }

        if (c.Kind is ColumnKind.Inet)
        {
            return "string?";
        }

        return N.ClrType(c);
    }

    private static string ResponseValue(Table t, Column c)
    {
        var p = "row." + N.Property(t, c);
        return c.Kind switch
        {
            ColumnKind.I18n or ColumnKind.Json => c.Required ? $"{p}.RootElement.Clone()" : $"{p}?.RootElement.Clone()",
            ColumnKind.Inet => $"{p}?.ToString()",
            _ => p,
        };
    }

    private static string RequestValue(Table t, Column c)
    {
        var p = "request." + N.Property(t, c);
        var (_, isValue) = N.BaseType(c);
        return c.Kind switch
        {
            ColumnKind.I18n or ColumnKind.Json => c.Required ? $"GeneratedEndpointSupport.ToDocument({p})!" : $"GeneratedEndpointSupport.ToDocument({p})",
            ColumnKind.Inet => $"{p} is null ? null : global::System.Net.IPAddress.Parse({p})",
            ColumnKind.TextArray or ColumnKind.UuidArray => c.Required ? $"{p} ?? []" : p,
            _ when c.Required && isValue => $"{p}!.Value",
            _ when c.Required => $"{p}!",
            _ => p,
        };
    }

    private static string EndpointRoot(string project, List<Table> tables)
    {
        var w = new CodeWriter();
        w.Line(Header)
            .Line("using global::Microsoft.AspNetCore.Http;")
            .Line("using global::Microsoft.AspNetCore.Routing;")
            .Line()
            .Line($"namespace Erp.{project}.Api.Generated;")
            .Line();
        w.Line($"/// <summary>Maps the generated endpoints of the {project} tables. Not called by the host until tenant resolution exists (S1.03).</summary>");
        w.Open($"public static class {project}GeneratedEndpoints");
        w.Open($"public static IEndpointRouteBuilder Map{project}GeneratedEndpoints(this IEndpointRouteBuilder app)");
        foreach (var t in tables)
        {
            w.Line($"global::{N.Namespace(t, "Api")}.{N.Entity(t)}Endpoints.Map(app);");
        }

        w.Line("return app;");
        w.Close().Close().Line();

        w.Line("/// <summary>Permission check, error mapping and JSON helpers shared by the generated endpoints. Titles are localization keys.</summary>");
        w.Open("internal static class GeneratedEndpointSupport");
        w.Open("public static async global::System.Threading.Tasks.Task<IResult> RunAsync(global::Erp.BuildingBlocks.Application.Security.IPermissionChecker permissions, string permission, global::System.Func<global::System.Threading.Tasks.Task<IResult>> action, global::System.Threading.CancellationToken cancellationToken)");
        w.Open("if (!await permissions.HasPermissionAsync(permission, cancellationToken).ConfigureAwait(false))");
        w.Line("return TypedResults.Problem(statusCode: StatusCodes.Status403Forbidden, title: \"errors.access.forbidden\");");
        w.Close().Line();
        w.Open("try");
        w.Line("return await action().ConfigureAwait(false);");
        w.Close();
        w.Open("catch (global::Erp.BuildingBlocks.Application.Data.ConcurrencyConflictException ex)");
        w.Line("return TypedResults.Problem(statusCode: StatusCodes.Status409Conflict, title: ex.ErrorCode);");
        w.Close();
        w.Open("catch (global::Erp.BuildingBlocks.Application.Data.DataConflictException ex)");
        w.Line("return TypedResults.Problem(statusCode: StatusCodes.Status409Conflict, title: ex.ErrorCode, detail: ex.Constraint);");
        w.Close();
        w.Open("catch (global::Erp.BuildingBlocks.Application.Data.DataValidationException ex)");
        w.Line("return TypedResults.Problem(statusCode: StatusCodes.Status400BadRequest, title: ex.ErrorCode, detail: ex.Constraint);");
        w.Close();
        w.Close().Line();
        w.Line("public static IResult NotFound() => TypedResults.Problem(statusCode: StatusCodes.Status404NotFound, title: \"errors.data.not_found\");");
        w.Line();
        w.Line("public static IResult Invalid(global::System.Collections.Generic.List<string> fields) =>");
        w.Line("    TypedResults.ValidationProblem(fields.ToDictionary(f => f, _ => new[] { \"errors.data.required_or_invalid\" }), title: \"errors.data.invalid_request\");");
        w.Line();
        w.Line("public static global::System.Text.Json.JsonDocument? ToDocument(global::System.Text.Json.JsonElement? value) =>");
        w.Line("    value is { } element ? global::System.Text.Json.JsonDocument.Parse(element.GetRawText()) : null;");
        w.Close();
        return w.ToString();
    }

    private static string Permissions(string project, List<Table> tables)
    {
        var w = new CodeWriter();
        w.Line(Header).Line($"namespace Erp.{project}.Contracts.Generated;").Line();
        w.Line($"/// <summary>Permissions of the generated {project} endpoints (module.resource.action), registered into iam.permissions (S1.06).</summary>");
        w.Open($"public static class {project}Permissions");
        w.Line("public static global::System.Collections.Generic.IReadOnlyList<global::Erp.BuildingBlocks.Contracts.Security.PermissionDefinition> All { get; } =");
        w.Line("[");
        foreach (var t in tables)
        {
            var sensitive = t.Columns.Exists(c => c.IsSensitive || c.Kind is ColumnKind.Money) ? "true" : "false";
            var moduleId = t.Module == "hrm" ? "hrm" : t.Schema;
            foreach (var action in Actions(t))
            {
                var code = N.Permission(t, action);
                w.Line($"    new({CodeWriter.CSharpString(code)}, {CodeWriter.CSharpString(moduleId)}, {CodeWriter.CSharpString("permissions." + code)}, {sensitive}),");
            }
        }

        w.Line("];");
        w.Close();
        return w.ToString();
    }
