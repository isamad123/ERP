    private static string Persistence(Table t)
    {
        var w = new CodeWriter();
        var e = N.EntityFull(t);
        w.Line(Header)
            .Line("using global::Microsoft.EntityFrameworkCore;")
            .Line("using global::Microsoft.EntityFrameworkCore.Metadata.Builders;")
            .Line()
            .Line($"namespace {N.Namespace(t, "Infrastructure")};")
            .Line();
        w.Line($"/// <summary>EF Core mapping of {CodeWriter.Xml(t.FullName)}.</summary>");
        w.Open($"internal sealed class {N.Entity(t)}Configuration : IEntityTypeConfiguration<{e}>");
        w.Open($"public void Configure(EntityTypeBuilder<{e}> builder)");
        w.Line($"builder.ToTable({CodeWriter.CSharpString(t.Name)}, {CodeWriter.CSharpString(t.Schema)});");
        var key = t.PrimaryKey.Select(k => "e." + N.Property(t, t.Column(k))).ToList();
        w.Line(key.Count == 1 ? $"builder.HasKey(e => {key[0]});" : $"builder.HasKey(e => new {{ {string.Join(", ", key)} }});");
        foreach (var c in t.Columns)
        {
            var line = $"builder.Property(e => e.{N.Property(t, c)}).HasColumnName({CodeWriter.CSharpString(c.Name)}).HasColumnType({CodeWriter.CSharpString(c.SqlType)})";
            if (c.Required && !N.BaseType(c).IsValueType)
            {
                line += ".IsRequired()";
            }

            if (t.PrimaryKey.Contains(c.Name))
            {
                line += ".ValueGeneratedNever()";
            }

            if (c.GeneratedExpression is not null)
            {
                line += $".HasComputedColumnSql({CodeWriter.CSharpString(c.GeneratedExpression)}, stored: true)";
            }

            if (c.Name == "row_version" && t.HasRowVersion)
            {
                line += ".IsConcurrencyToken()";
            }

            w.Line(line + ";");
        }

        w.Close().Close();

        if (HasRepository(t))
        {
            w.Line();
            var baseClass = t.IsSoftDeleted && t.HasRowVersion ? "GeneratedSoftDeleteRepository"
                : t.HasRowVersion ? "GeneratedMutableRepository"
                : "GeneratedRepository";
            w.Line($"/// <summary>Generated repository of {CodeWriter.Xml(t.FullName)}; reads pass through the data-scope filter.</summary>");
            w.Line($"internal sealed class {N.Entity(t)}Repository(");
            w.Line($"    {N.DbContextName(t)} context,");
            w.Line("    global::Erp.BuildingBlocks.Domain.Time.IClock clock,");
            w.Line("    global::Erp.BuildingBlocks.Application.Security.ICurrentActor actor,");
            w.Line("    global::Erp.BuildingBlocks.Application.Security.IDataScopeFilter scope)");
            w.Line($"    : global::Erp.BuildingBlocks.Infrastructure.Persistence.{baseClass}<{e}>(context, clock, actor, scope, {AccessFull(t)}.Scope),");
            w.Open($"    {N.RepositoryInterfaceFull(t)}");
            w.Open($"public async global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> ListAsync({N.FilterFull(t)} filter, global::Erp.BuildingBlocks.Application.Data.PageRequest page, global::System.Threading.CancellationToken cancellationToken)");
            w.Line("global::System.ArgumentNullException.ThrowIfNull(filter);");
            w.Line("var query = await QueryAsync(cancellationToken).ConfigureAwait(false);");
            foreach (var c in FilterColumns(t))
            {
                var p = N.Property(t, c);
                var local = CodeWriter.Identifier(Naming.Camel(c.Name) + "Filter");
                var pattern = N.BaseType(c).IsValueType ? $"{{ }} {local}" : $"{{ }} {local}";
                w.Open($"if (filter.{p} is {pattern})");
                w.Line($"query = query.Where(e => e.{p} == {local});");
                w.Close();
            }

            if (t.IsEffectiveDated)
            {
                w.Open("if (filter.AsOf is { } asOf)");
                w.Line("query = query.Where(e => e.ValidFrom <= asOf && (e.ValidTo == null || e.ValidTo > asOf));");
                w.Close();
            }

            var search = SearchColumns(t);
            if (search.Count > 0)
            {
                w.Open("if (!string.IsNullOrWhiteSpace(filter.Search))");
                w.Line("var pattern = global::Erp.BuildingBlocks.Infrastructure.Persistence.ListSearch.Pattern(filter.Search);");
                const string like = "global::Microsoft.EntityFrameworkCore.EF.Functions.ILike";
                const string escape = "global::Erp.BuildingBlocks.Infrastructure.Persistence.ListSearch.Escape";
                var terms = search.SelectMany(c => c.Kind is ColumnKind.I18n
                    ? SearchLanguages.Select(l => $"{like}(e.{N.Property(t, c)}.RootElement.GetProperty({CodeWriter.CSharpString(l)}).GetString()!, pattern, {escape})")
                    : [$"{like}(e.{N.Property(t, c)}{(c.Required ? string.Empty : "!")}, pattern, {escape})"]);
                w.Line($"query = query.Where(e => {string.Join(" || ", terms)});");
                w.Close();
            }

            w.Line(SortColumns(t).Count > 0
                ? "return await Sorts.PageAsync(Context.Set<" + e + ">().AsNoTracking(), query, filter.Sort, page, cancellationToken).ConfigureAwait(false);"
                : "return await PageAsync(query, page, cancellationToken).ConfigureAwait(false);");
            w.Close();
            if (SortColumns(t) is { Count: > 0 } sorts)
            {
                w.Line();
                w.Line("/// <summary>Sort keys of the list endpoint: indexed columns (S1.12c, ruling Q11).</summary>");
                var chain = string.Concat(sorts.Select(s => s.Lower
                    ? $".Text({CodeWriter.CSharpString(Naming.Camel(s.Column.Name))}, e => e.{N.Property(t, s.Column)})"
                    : $".Key({CodeWriter.CSharpString(Naming.Camel(s.Column.Name))}, e => e.{N.Property(t, s.Column)})"));
                w.Line($"private static readonly global::Erp.BuildingBlocks.Infrastructure.Persistence.ListSorts<{e}> Sorts = new global::Erp.BuildingBlocks.Infrastructure.Persistence.ListSorts<{e}>(){chain};");
            }
            if (t.IsCompanyScoped)
            {
                w.Line();
                w.Line($"public async global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> ListByCompanyAsync(global::System.Guid companyId, global::Erp.BuildingBlocks.Application.Data.PageRequest page, global::System.Threading.CancellationToken cancellationToken) =>");
                w.Line("    await PageAsync((await QueryAsync(cancellationToken).ConfigureAwait(false)).Where(e => e.CompanyId == companyId), page, cancellationToken).ConfigureAwait(false);");
            }

            foreach (var finder in Finders(t))
            {
                w.Line();
                w.Open($"public async global::System.Threading.Tasks.Task<global::System.Collections.Generic.IReadOnlyList<{e}>> {finder.Name}({finder.Parameters}, global::System.Threading.CancellationToken cancellationToken)");
                w.Line("var query = await QueryAsync(cancellationToken).ConfigureAwait(false);");
                w.Line($"return await query.Where(e => {finder.Predicate}).OrderBy(e => e.Id).Take(global::Erp.BuildingBlocks.Application.Data.PageRequest.MaxLimit).ToListAsync(cancellationToken).ConfigureAwait(false);");
                w.Close();
            }

            w.Close();
        }

        return w.ToString();
    }

    private sealed record Finder(string Name, string Parameters, string Predicate, IReadOnlyList<string> Items);

    /// <summary>One lookup per listed unique key and index (README: "standard queries by listed indexes").</summary>
    private static List<Finder> Finders(Table t)
    {
        var result = new List<Finder>();
        var keys = t.Uniques.Select(u => u.Items).Concat(t.Indexes.Where(i => i.Purpose == "listed in the data design").Select(i => i.Items));
        foreach (var items in keys)
        {
            var columns = items.Select(i => t.Column(DesignLoader.ItemColumn(i))).ToList();
            if (items.SequenceEqual(["id"]) || items.SequenceEqual(["company_id"]) || items.SequenceEqual(["company_id", "id"])
                || columns.Exists(c => c.Kind is ColumnKind.Json or ColumnKind.I18n or ColumnKind.TextArray or ColumnKind.UuidArray or ColumnKind.Bytea or ColumnKind.Encrypted or ColumnKind.Hmac)
                || result.Exists(r => r.Items.SequenceEqual(items)))
            {
                continue;
            }

            var name = "FindBy" + string.Join("And", columns.Select(c => Naming.Pascal(c.Name))) + "Async";
            if (result.Exists(r => r.Name == name))
            {
                continue;
            }

            var parameters = string.Join(", ", columns.Select(c => $"{N.ClrType(c)} {CodeWriter.Identifier(Naming.Camel(c.Name))}"));
            var predicate = string.Join(" && ", items.Select((item, i) =>
            {
                var c = columns[i];
                var p = CodeWriter.Identifier(Naming.Camel(c.Name));
                return item.StartsWith("lower(", StringComparison.Ordinal)
                    ? $"e.{N.Property(t, c)}!.ToLower() == {p}!.ToLower()"
                    : $"e.{N.Property(t, c)} == {p}";
            }));
            result.Add(new Finder(name, parameters, predicate, items));
        }

        return result;
    }

    private static string DbContext(string module, List<Table> tables)
    {
        var sample = tables[0];
        var name = N.DbContextName(sample);
        var ns = module switch
        {
            "hrm" => "Erp.Hrm.Infrastructure.Generated",
            "controlplane" => "Erp.Kernel.Infrastructure.ControlPlane.Generated",
            _ => "Erp.Kernel.Infrastructure.Generated",
        };
        var w = new CodeWriter();
        w.Line(Header).Line("using global::Microsoft.EntityFrameworkCore;").Line("using global::Microsoft.Extensions.DependencyInjection;").Line().Line($"namespace {ns};").Line();
        var database = module == "controlplane" ? "control-plane database" : "customer database";
        w.Line($"/// <summary>EF Core context of the {module} tables in the {database} (generated mapping; SQL migrations own the schema).</summary>");
        w.Open($"public sealed partial class {name}(DbContextOptions<{name}> options) : DbContext(options)");
        w.Open("protected override void OnModelCreating(ModelBuilder modelBuilder)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(modelBuilder);");
        foreach (var t in tables)
        {
            w.Line($"modelBuilder.ApplyConfiguration(new global::{N.Namespace(t, "Infrastructure")}.{N.Entity(t)}Configuration());");
        }

        w.Close().Close().Line();
        var prefix = module switch { "hrm" => "Hrm", "controlplane" => "ControlPlane", _ => "Kernel" };
        w.Line($"/// <summary>Registers the generated repositories of the {module} tables. The DbContext itself is registered by the host (tenant connection, S1.03).</summary>");
        w.Open($"public static class {prefix}GeneratedServices");
        w.Open($"public static IServiceCollection Add{prefix}GeneratedRepositories(this IServiceCollection services)");
        foreach (var t in tables.Where(HasRepository))
        {
            w.Line($"services.AddScoped<{N.RepositoryInterfaceFull(t)}, global::{N.Namespace(t, "Infrastructure")}.{N.Entity(t)}Repository>();");
        }

        w.Line("return services;");
        w.Close().Close();
        return w.ToString();
    }

    // ---------------------------------------------------------------- Application

    private static string RepositoryInterface(Table t)
    {
        var e = N.EntityFull(t);
        var baseInterface = t.IsSoftDeleted && t.HasRowVersion ? "ISoftDeleteRepository"
            : t.HasRowVersion ? "IMutableRepository"
            : "IRepository";
        var w = new CodeWriter();
        w.Line(Header).Line($"namespace {N.Namespace(t, "Application")};").Line();
        w.Line($"/// <summary>Equality filters for listing {CodeWriter.Xml(t.FullName)} (foreign keys, status and is_active). Null means no filter.</summary>");
        w.Open($"public sealed record {N.Filter(t)}");
        foreach (var c in FilterColumns(t))
        {
            var (type, _) = N.BaseType(c);
            w.Line($"public {type}? {N.Property(t, c)} {{ get; init; }}");
        }

        ListOptionProperties(w, t, filter: true);
        w.Close().Line();
        w.Line($"/// <summary>Generated repository of {CodeWriter.Xml(t.FullName)}.</summary>");
        w.Open($"public interface {N.RepositoryInterface(t)} : global::Erp.BuildingBlocks.Application.Data.{baseInterface}<{e}>");
