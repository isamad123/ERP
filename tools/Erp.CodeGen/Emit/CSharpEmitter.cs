                w.Line($"row.{N.Property(t, initialStatus)} = {CodeWriter.CSharpString(initialStatus.EnumValues[0])};");
                w.Close();
            }

            w.Line("return denied;");
            w.Close();
        }

        w.Close();
        return w.ToString();
    }

