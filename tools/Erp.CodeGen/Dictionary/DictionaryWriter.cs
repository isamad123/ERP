using System.Globalization;
using System.Text;
using Erp.BuildingBlocks.Infrastructure.Migrations;
using Erp.CodeGen.Design;
using Erp.CodeGen.Emit;
using Npgsql;

namespace Erp.CodeGen.Dictionary;

/// <summary>
/// The data dictionary is built from a real database after the generated migrations run (slice S1.02 item 7), so it
/// describes what PostgreSQL actually holds. CI rebuilds it and fails if it differs from the committed file.
/// </summary>
public static class DictionaryWriter
{
    public const string RelativePath = "docs/data-design/generated/data-dictionary.md";

    public static async Task<string> BuildAndWriteAsync(DesignModel model, string root, string adminConnectionString, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(model);
        var tenant = await ScratchDatabase.CreateAsync(adminConnectionString, "erp_codegen_dictionary_tenant", cancellationToken).ConfigureAwait(false);
        var controlPlane = await ScratchDatabase.CreateAsync(adminConnectionString, "erp_codegen_dictionary_cp", cancellationToken).ConfigureAwait(false);
        try
        {
            await SqlScriptRunner.ApplyAsync(tenant.ConnectionString, SqlScriptRunner.Scripts(Path.Combine(root, SqlEmitter.KernelMigrations), Path.Combine(root, SqlEmitter.HrmMigrations)), cancellationToken).ConfigureAwait(false);
            await SqlScriptRunner.ApplyAsync(controlPlane.ConnectionString, SqlScriptRunner.Scripts(Path.Combine(root, SqlEmitter.ControlPlaneMigrations)), cancellationToken).ConfigureAwait(false);
            var tenantSnapshot = await ReadAsync(tenant.ConnectionString, cancellationToken).ConfigureAwait(false);
            var cpSnapshot = await ReadAsync(controlPlane.ConnectionString, cancellationToken).ConfigureAwait(false);
            var path = Path.Combine(root, RelativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            await File.WriteAllTextAsync(path, Render(model, tenantSnapshot, cpSnapshot), new UTF8Encoding(false), cancellationToken).ConfigureAwait(false);
            return path;
        }
        finally
        {
            await tenant.DropAsync(cancellationToken).ConfigureAwait(false);
            await controlPlane.DropAsync(cancellationToken).ConfigureAwait(false);
        }
    }

    private static async Task<CatalogSnapshot> ReadAsync(string connectionString, CancellationToken cancellationToken)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(cancellationToken).ConfigureAwait(false);
        return await CatalogReader.ReadAsync(connection, cancellationToken).ConfigureAwait(false);
    }

    public static string Render(DesignModel model, CatalogSnapshot tenant, CatalogSnapshot controlPlane)
    {
        ArgumentNullException.ThrowIfNull(model);
        ArgumentNullException.ThrowIfNull(tenant);
        ArgumentNullException.ThrowIfNull(controlPlane);
        var b = new StringBuilder();
        b.Append("<!-- <auto-generated> Built by `dotnet run --project tools/Erp.CodeGen -- dictionary` from a PostgreSQL database after the generated\n");
        b.Append("     migrations ran (slice S1.02). Do not edit by hand. </auto-generated> -->\n");
        b.Append("# Data dictionary (generated from the live database)\n\n");
        b.Append(Naming.Invariant($"Release {model.Settings.Release}. Customer database: {tenant.Tables.Count} tables. Control-plane database: {controlPlane.Tables.Count} tables. "));
        b.Append("Each customer database also holds the monthly partitions of the partitioned tables (counted per table below).\n\n");
        b.Append("| Database | Schema | Tables |\n| --- | --- | --- |\n");
        foreach (var (name, snapshot) in new[] { ("customer", tenant), ("control plane", controlPlane) })
        {
            foreach (var schema in snapshot.Tables.GroupBy(t => t.Schema))
            {
                b.Append(Naming.Invariant($"| {name} | {schema.Key} | {schema.Count()} |\n"));
            }
        }

        b.Append('\n');
        AppendDatabase(b, "Customer database", tenant);
        AppendDatabase(b, "Control-plane database", controlPlane);
        return b.ToString();
    }

    private static void AppendDatabase(StringBuilder b, string title, CatalogSnapshot snapshot)
    {
        b.Append("## ").Append(title).Append("\n\n");
        foreach (var table in snapshot.Tables)
        {
            b.Append("### ").Append(table.FullName).Append("\n\n");
            if (table.Comment is not null)
            {
                b.Append(Cell(table.Comment)).Append("\n\n");
            }

            if (table.IsPartitioned)
            {
                b.Append(Naming.Invariant($"Partitioned by range; {table.PartitionCount} partitions.\n\n"));
            }

            b.Append("| Column | Type | Null | Default | Notes |\n| --- | --- | --- | --- | --- |\n");
            foreach (var c in table.Columns)
            {
                var defaultText = c.Generated is not null ? "generated: " + c.Generated : c.Default ?? string.Empty;
                b.Append(CultureInfo.InvariantCulture, $"| {c.Name} | {c.Type} | {(c.NotNull ? "no" : "yes")} | {Cell(defaultText)} | {Cell(c.Comment ?? string.Empty)} |\n");
            }

            b.Append('\n');
            if (table.Constraints.Count > 0)
            {
                b.Append("Constraints:\n\n");
                foreach (var k in table.Constraints)
                {
                    b.Append("- `").Append(k.Name).Append("` ").Append(Cell(k.Definition)).Append('\n');
                }

                b.Append('\n');
            }

            if (table.Indexes.Count > 0)
            {
                b.Append("Indexes:\n\n");
                foreach (var i in table.Indexes)
                {
                    b.Append("- `").Append(i.Name).Append("` ").Append(Cell(i.Definition)).Append('\n');
                }

                b.Append('\n');
            }

            if (table.Triggers.Count > 0)
            {
                b.Append("Triggers:\n\n");
                foreach (var t in table.Triggers)
                {
                    b.Append("- `").Append(t.Name).Append("` ").Append(Cell(t.Definition)).Append('\n');
                }

                b.Append('\n');
            }
        }

        if (snapshot.Functions.Count > 0)
        {
            b.Append("### Functions\n\n");
            foreach (var f in snapshot.Functions)
            {
                b.Append("- `").Append(f.Schema).Append('.').Append(f.Name).Append("` ").Append(Cell(f.Comment ?? string.Empty)).Append('\n');
            }

            b.Append('\n');
        }
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}

/// <summary>A throw-away database on the given server, created for one run and dropped afterwards.</summary>
public sealed class ScratchDatabase
{
    private readonly string _adminConnectionString;

    private ScratchDatabase(string adminConnectionString, string name, string connectionString)
    {
        _adminConnectionString = adminConnectionString;
        Name = name;
        ConnectionString = connectionString;
    }

    public string Name { get; }

    public string ConnectionString { get; }

    public static async Task<ScratchDatabase> CreateAsync(string adminConnectionString, string name, CancellationToken cancellationToken)
    {
        if (!Naming.IsIdentifier(name))
        {
            throw new ArgumentException("database name must be a lower-case identifier", nameof(name));
        }

        await ExecuteAsync(adminConnectionString, $"drop database if exists {name} with (force)", cancellationToken).ConfigureAwait(false);
        await ExecuteAsync(adminConnectionString, $"create database {name}", cancellationToken).ConfigureAwait(false);
        var builder = new NpgsqlConnectionStringBuilder(adminConnectionString) { Database = name, Pooling = false };
        return new ScratchDatabase(adminConnectionString, name, builder.ConnectionString);
    }

    public Task DropAsync(CancellationToken cancellationToken) =>
        ExecuteAsync(_adminConnectionString, $"drop database if exists {Name} with (force)", cancellationToken);

    private static async Task ExecuteAsync(string connectionString, string sql, CancellationToken cancellationToken)
    {
        var builder = new NpgsqlConnectionStringBuilder(connectionString) { Pooling = false };
        await using var connection = new NpgsqlConnection(builder.ConnectionString);
        await connection.OpenAsync(cancellationToken).ConfigureAwait(false);
#pragma warning disable CA2100 // The database name is checked to be a plain identifier above.
        await using var command = new NpgsqlCommand(sql, connection);
#pragma warning restore CA2100
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }
}
