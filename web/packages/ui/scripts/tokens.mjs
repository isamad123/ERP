#!/usr/bin/env node
// Design tokens → CSS variables, with the contrast gate of spec 13 FR-UX-TOK-02 (slice S1.12a, Build item 2).
// Usage: node tokens.mjs            write src/tokens/tokens.css (fails, writing nothing, when a pair is below its limit)
//        node tokens.mjs --check    check only
//        node tokens.mjs --self-test  prove the gate fails on a deliberately bad pair and passes a good one
// Limits (WCAG 2.2): text 4.5:1; large text and boundaries (borders, focus rings, control edges) 3:1.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
export const LIMITS = { text: 4.5, large: 3, boundary: 3 };

/** Relative luminance of a #rrggbb colour (WCAG 2.2). */
export function luminance(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`not a #rrggbb colour: ${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Every pair in every theme; returns the failures (empty = all pass). */
export function check(tokens) {
  const failures = [];
  for (const [theme, colours] of Object.entries(tokens.themes)) {
    for (const { fg, bg, kind } of tokens.pairs) {
      if (!(fg in colours) || !(bg in colours)) {
        failures.push(`${theme}: pair ${fg} on ${bg} names a token the theme does not define`);
        continue;
      }
      const ratio = contrast(colours[fg], colours[bg]);
      const limit = LIMITS[kind];
      if (limit === undefined) failures.push(`${theme}: unknown pair kind ${kind}`);
      else if (ratio < limit) failures.push(`${theme}: ${fg} ${colours[fg]} on ${bg} ${colours[bg]} is ${ratio.toFixed(2)}:1, below ${limit}:1 (${kind})`);
    }
  }
  return failures;
}

const block = (selector, vars) => `${selector} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;

export function css(tokens) {
  const out = ['/* <auto-generated> by packages/ui/scripts/tokens.mjs from tokens/tokens.json (slice S1.12a). Do not edit. </auto-generated> */\n'];
  out.push(block(':root', { ...tokens.scale, ...tokens.density.standard, ...tokens.themes.light,
    'font-body': 'var(--font-latin)', 'line-height-body': 'var(--line-height-latin)', 'line-height-tight': 'var(--line-height-tight-latin)' }));
  out.push(':root { color-scheme: light; }\n');
  for (const [name, vars] of Object.entries(tokens.density)) out.push(block(`:root[data-density="${name}"]`, vars));
  out.push(`@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', tokens.themes.dark)}:root:not([data-theme]) { color-scheme: dark; }\n}\n`);
  out.push(`@media (prefers-contrast: more) {\n${block(':root:not([data-theme])', tokens.themes.contrast)}}\n`);
  out.push(`@media (forced-colors: active) {\n:root { --focus-width: 3px; }\n}\n`);
  for (const [name, vars] of Object.entries(tokens.themes)) {
    out.push(block(`:root[data-theme="${name}"]`, vars));
    out.push(`:root[data-theme="${name}"] { color-scheme: ${name === 'light' ? 'light' : 'dark'}; }\n`);
  }
  // Arabic-script text (Urdu) needs its own face and more line height (FR-UX-TOK-12).
  out.push(block(':root:lang(ur)', { 'font-body': 'var(--font-arabic)', 'line-height-body': 'var(--line-height-arabic)', 'line-height-tight': 'var(--line-height-tight-arabic)' }));
  out.push('@media (prefers-reduced-motion: reduce) {\n:root { --motion-fast: 0ms; --motion-medium: 0ms; }\n}\n');
  return out.join('\n');
}

function main(args) {
  if (args.includes('--self-test')) {
    const good = { themes: { t: { a: '#000000', b: '#ffffff' } }, pairs: [{ fg: 'a', bg: 'b', kind: 'text' }] };
    const bad = { themes: { t: { a: '#777777', b: '#888888' } }, pairs: [{ fg: 'a', bg: 'b', kind: 'text' }] };
    const boundary = { themes: { t: { a: '#a0a0a0', b: '#ffffff' } }, pairs: [{ fg: 'a', bg: 'b', kind: 'boundary' }] };
    const results = [check(good).length === 0, check(bad).length === 1, check(boundary).length === 1, Math.abs(contrast('#000000', '#ffffff') - 21) < 1e-9];
    console.log(`token contrast self-test: ${results.filter(Boolean).length}/${results.length} passed`);
    return results.every(Boolean) ? 0 : 1;
  }

  const file = args.find((a) => a.startsWith('--tokens='))?.slice(9) ?? join(root, 'tokens', 'tokens.json');
  const tokens = JSON.parse(readFileSync(file, 'utf8'));
  const failures = check(tokens);
  if (failures.length > 0) {
    console.error('Token contrast check FAILED (spec 13 FR-UX-TOK-02):');
    for (const f of failures) console.error('  - ' + f);
    return 1;
  }

  const pairs = tokens.pairs.length * Object.keys(tokens.themes).length;
  if (args.includes('--check')) {
    console.log(`Token contrast check passed: ${pairs} pairs in ${Object.keys(tokens.themes).length} themes.`);
    return 0;
  }

  mkdirSync(join(root, 'src', 'tokens'), { recursive: true });
  writeFileSync(join(root, 'src', 'tokens', 'tokens.css'), css(tokens));
  console.log(`tokens.css written; contrast check passed (${pairs} pairs).`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit(main(process.argv.slice(2)));
